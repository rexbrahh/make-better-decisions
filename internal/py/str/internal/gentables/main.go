// Command gentables writes internal/py/str/tables.go and internal/py/re/classes.go from the per-code-point
// str data of the CPython named by AGENT_DECISIONS_PYTHON. Run it with go generate ./internal/py/str.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"strings"
)

// dumpScript prints, as one JSON object, the code point ranges where each str predicate holds and the
// code points whose lower() or casefold() differs from the code point itself.
//
// CPython does not expose the Cased and Case_Ignorable properties that str.lower() uses for a final sigma,
// so the script reads them back from lower() itself. A code point c is case-ignorable or cased when
// "A" + c + "Σ" lowers to a final "ς". It is cased and not case-ignorable when "AΣ" + c + "1" keeps a
// medial "σ". The final-sigma test skips case-ignorable code points before it asks whether one is cased,
// so these two sets are all that str.lower() can observe.
const dumpScript = `
import json, sys, unicodedata
assert sys.version_info[:2] == (3, 15), sys.version

def ranges(predicate):
    found, start = [], None
    for cp in range(0x110000):
        if predicate(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            found.append((start, cp - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found

def mapping(method):
    found = []
    for cp in range(0x110000):
        mapped = method(chr(cp))
        if mapped != chr(cp):
            assert not any(0xD800 <= ord(c) <= 0xDFFF for c in mapped), hex(cp)
            found.append({"code_point": cp, "result": [ord(c) for c in mapped]})
    return found

ignorable_or_cased = lambda c: ("A" + c + "Σ").lower()[-1] == "ς"
cased = lambda c: ("AΣ" + c + "1").lower()[1] == "σ"
json.dump({
    "python": sys.version.split()[0],
    "unicode": unicodedata.unidata_version,
    "space": ranges(str.isspace),
    "printable": ranges(str.isprintable),
    "alnum": ranges(str.isalnum),
    "word": ranges(lambda c: c.isalnum() or c == "_"),
    "decimal": ranges(str.isdecimal),
    "cased": ranges(cased),
    "case_ignorable": ranges(lambda c: ignorable_or_cased(c) and not cased(c)),
    "lower": mapping(str.lower),
    "casefold": mapping(str.casefold),
}, sys.stdout)
`

type span [2]rune

type mapped struct {
	CodePoint rune   `json:"code_point"`
	Result    []rune `json:"result"`
}

type data struct {
	Python, Unicode                               string
	Space, Printable, Alnum, Word, Decimal, Cased []span
	CaseIgnorable                                 []span `json:"case_ignorable"`
	Lower, Casefold                               []mapped
}

func main() {
	python := os.Getenv("AGENT_DECISIONS_PYTHON")
	if python == "" {
		log.Fatal("set AGENT_DECISIONS_PYTHON to a CPython 3.15 interpreter")
	}
	command := exec.Command(python, "-I", "-c", dumpScript)
	command.Stderr = os.Stderr
	output, err := command.Output()
	if err != nil {
		log.Fatalf("%s: %v", python, err)
	}
	var d data
	if err := json.Unmarshal(output, &d); err != nil {
		log.Fatal(err)
	}
	header := fmt.Sprintf("// Code generated by gentables from CPython %s (Unicode %s). DO NOT EDIT.\n"+
		"// Regenerate: AGENT_DECISIONS_PYTHON=<python3.15> go generate ./internal/py/str\n\n", d.Python, d.Unicode)
	write("tables.go", header+strTables(d))
	write("../re/classes.go", header+reClasses(d))
}

func write(path, source string) {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		log.Fatalf("%s: %v", path, err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

func strTables(d data) string {
	var b bytes.Buffer
	b.WriteString("package str\n\nimport \"unicode\"\n\n")
	rangeTable(&b, "spaceTable", "holds the code points where str.isspace() is true.", d.Space)
	rangeTable(&b, "printableTable", "holds the code points where str.isprintable() is true.", d.Printable)
	rangeTable(&b, "alnumTable", "holds the code points where str.isalnum() is true.", d.Alnum)
	rangeTable(&b, "casedTable", "holds the cased code points that are not case-ignorable.", d.Cased)
	rangeTable(&b, "caseIgnorableTable", "holds the case-ignorable code points.", d.CaseIgnorable)
	caseTables(&b, "lower", "str.lower()", d.Lower)
	caseTables(&b, "casefold", "str.casefold()", d.Casefold)
	return b.String()
}

func rangeTable(b *bytes.Buffer, name, doc string, spans []span) {
	fmt.Fprintf(b, "// %s %s\nvar %s = &unicode.RangeTable{\n", name, doc, name)
	var r16, r32 []string
	for _, s := range spans {
		if s[1] <= 0xFFFF {
			r16 = append(r16, fmt.Sprintf("{%#04x, %#04x, 1}", s[0], s[1]))
			continue
		}
		if s[0] <= 0xFFFF {
			r16 = append(r16, fmt.Sprintf("{%#04x, 0xffff, 1}", s[0]))
			s[0] = 0x10000
		}
		r32 = append(r32, fmt.Sprintf("{%#04x, %#04x, 1}", s[0], s[1]))
	}
	if len(r16) > 0 {
		fmt.Fprintf(b, "R16: []unicode.Range16{\n%s},\n", lines(r16, 4))
	}
	if len(r32) > 0 {
		fmt.Fprintf(b, "R32: []unicode.Range32{\n%s},\n", lines(r32, 4))
	}
	b.WriteString("}\n\n")
}

// caseTables writes the single code point results of a case mapping as caseRange runs, and the longer
// results as a map. A run holds entries that are adjacent in code point order, so no other changed code
// point lies inside it.
func caseTables(b *bytes.Buffer, name, method string, entries []mapped) {
	var runs, special []string
	for i := 0; i < len(entries); {
		first := entries[i]
		if len(first.Result) != 1 {
			special = append(special, fmt.Sprintf("%#04x: %+q,", first.CodePoint, string(first.Result)))
			i++
			continue
		}
		delta := first.Result[0] - first.CodePoint
		last, stride := first.CodePoint, rune(1)
		for i++; i < len(entries); i++ {
			next := entries[i]
			if len(next.Result) != 1 || next.Result[0]-next.CodePoint != delta {
				break
			}
			if last == first.CodePoint {
				stride = next.CodePoint - last
			} else if next.CodePoint-last != stride {
				break
			}
			last = next.CodePoint
		}
		runs = append(runs, fmt.Sprintf("{%#04x, %#04x, %d, %d}", first.CodePoint, last, stride, delta))
	}
	fmt.Fprintf(b, "// %sRanges maps the code points whose %s is one other code point.\n", name, method)
	fmt.Fprintf(b, "var %sRanges = []caseRange{\n%s}\n\n", name, lines(runs, 4))
	fmt.Fprintf(b, "// %sSpecial maps the code points whose %s has more than one code point.\n", name, method)
	fmt.Fprintf(b, "var %sSpecial = map[rune]string{\n%s\n}\n\n", name, strings.Join(special, "\n"))
}

func reClasses(d data) string {
	var b bytes.Buffer
	b.WriteString("package re\n\n")
	class(&b, "Space", `\s`, `\S`, "the code points where str.isspace() is true", "SRE_UNI_IS_SPACE", d.Space)
	class(&b, "Word", `\w`, `\W`, `the code points where str.isalnum() is true, and "_"`, "SRE_UNI_IS_WORD", d.Word)
	class(&b, "Digit", `\d`, `\D`, "the code points where str.isdecimal() is true", "SRE_UNI_IS_DIGIT", d.Decimal)
	return b.String()
}

func class(b *bytes.Buffer, name, escape, notEscape, members, macro string, spans []span) {
	var items []string
	for _, s := range spans {
		if s[0] == s[1] {
			items = append(items, fmt.Sprintf(`\x{%x}`, s[0]))
		} else {
			items = append(items, fmt.Sprintf(`\x{%x}-\x{%x}`, s[0], s[1]))
		}
	}
	body := make([]string, 0, len(items)/8+1)
	for start := 0; start < len(items); start += 8 {
		body = append(body, "`"+strings.Join(items[start:min(start+8, len(items))], "")+"`")
	}
	set := strings.Join(body, " +\n\t")
	fmt.Fprintf(b, "// %s is a bracket expression that matches the code points Python's %s matches in a str pattern:\n"+
		"// %s.\n//\n// py: Modules/_sre/sre.c %s (Python 3.15)\nconst %s = \"[\" +\n\t%s + \"]\"\n\n",
		name, escape, members, macro, name, set)
	fmt.Fprintf(b, "// Not%s is a bracket expression that matches the code points Python's %s matches: those that %s does not match.\n"+
		"//\n// py: Modules/_sre/sre.c %s (Python 3.15)\nconst Not%s = \"[^\" +\n\t%s + \"]\"\n\n",
		name, notEscape, escape, macro, name, set)
}

func lines(items []string, perLine int) string {
	var b strings.Builder
	for start := 0; start < len(items); start += perLine {
		b.WriteString(strings.Join(items[start:min(start+perLine, len(items))], ", ") + ",\n")
	}
	return b.String()
}
